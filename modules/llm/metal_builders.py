"""Generates ggml-metal-embed.gen.cpp, which embeds one Metal source per
kernel library for ggml-metal-device.m when GGML_METAL_EMBED_LIBRARY is defined.

ggml-metal-device.m lists its libraries once, in the GGML_METAL_LIBS X-macro,
and reads each one as the bytes between ggml_metallib_<name>_start and
ggml_metallib_<name>_end. Those two symbols must enclose one contiguous run of
bytes, so the generated file emits each library as a top-level asm block with
both labels around an .ascii payload. That is the layout llama.cpp's
CMakeLists.txt produces with .incbin, without a side file per kind.

The per-kind source is built the same way the CMake recipe builds it:
  1. concatenate kernels/common.h, the shared headers the kernel includes,
     and the kernel source;
  2. drop the internal #include lines and every #pragma once;
  3. replace the __embed_ggml-common.h__ line with ggml/src/ggml-common.h;
  4. replace the #include "ggml-metal-impl.h" line with ggml-metal-impl.h.

    python3 modules/llm/metal_builders.py --check <cmake-build-dir>
compares every kind byte for byte with the sources a CMake build of the same
tree wrote to ggml/src/ggml-metal/autogenerated/.
"""

import os
import re
import sys

# Optional shared headers, in the order CMake prepends them.
OPTIONAL_HEADERS = ("dequantize.h", "quantize.h", "fa_common.metal", "fa_vec_common.metal")
DROPPED_INCLUDES = ("common.h",) + OPTIONAL_HEADERS


def library_kinds(device_m: str) -> list:
    """Return the kernel library names from the GGML_METAL_LIBS X-macro."""
    text = open(device_m, encoding="utf-8").read()
    m = re.search(r"#define GGML_METAL_LIBS\s*\\\n((?:.*\\\n)*.*\n)", text)
    if not m:
        raise RuntimeError(f"GGML_METAL_LIBS not found in {device_m}")
    kinds = re.findall(r"X\(\s*\w+\s*,\s*(\w+)\s*\)", m.group(1))
    if not kinds:
        raise RuntimeError(f"GGML_METAL_LIBS in {device_m} lists no libraries")
    return kinds


def merge_kind(kernels_dir: str, kind: str, common_h: str, impl_h: str) -> str:
    """Build the self-contained Metal source for one library kind."""
    src = open(os.path.join(kernels_dir, kind + ".metal"), encoding="utf-8").read()
    parts = [os.path.join(kernels_dir, "common.h")]
    for hdr in OPTIONAL_HEADERS:
        if f'#include "{hdr}"' in src:
            parts.append(os.path.join(kernels_dir, hdr))
    text = "".join(open(p, encoding="utf-8").read() for p in parts) + src

    common = open(common_h, encoding="utf-8").read()
    impl = open(impl_h, encoding="utf-8").read()
    out = []
    for line in text.splitlines(keepends=True):
        if "#pragma once" in line or any(f'#include "{h}"' in line for h in DROPPED_INCLUDES):
            continue
        if "__embed_ggml-common.h__" in line:
            out.append(common)
        elif '#include "ggml-metal-impl.h"' in line:
            out.append(impl)
        else:
            out.append(line)
    return "".join(out)


def _asm_ascii(data: bytes) -> list:
    """Encode bytes as assembler .ascii directives, one per source line."""
    lines = []
    for chunk in data.splitlines(keepends=True):
        esc = []
        for b in chunk:
            if b == ord('"'):
                esc.append('\\"')
            elif b == ord("\\"):
                esc.append("\\\\")
            elif 32 <= b < 127:
                esc.append(chr(b))
            else:
                esc.append(f"\\{b:03o}")
        lines.append('.ascii "' + "".join(esc) + '"')
    return lines


def _c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '\\n"'


def render_embed(kernels_dir: str, kinds: list, common_h: str, impl_h: str) -> str:
    out = [
        "/* Auto-generated by modules/llm/metal_builders.py; do not edit. */",
        "/* One embedded Metal source per GGML_METAL_LIBS entry.             */",
        "",
    ]
    for kind in kinds:
        data = merge_kind(kernels_dir, kind, common_h, impl_h).encode("utf-8")
        asm = [
            ".section __DATA,__ggml_metallib",
            f".globl _ggml_metallib_{kind}_start",
            f"_ggml_metallib_{kind}_start:",
            *_asm_ascii(data),
            f".globl _ggml_metallib_{kind}_end",
            f"_ggml_metallib_{kind}_end:",
            ".text",
        ]
        out.append(f"// {kind}: {len(data)} bytes")
        out.append("__asm__(")
        out.extend("    " + _c_string(a) for a in asm)
        out.append(");")
        out.append("")
    return "\n".join(out)


def _paths(metal_dir: str):
    device_m = os.path.join(metal_dir, "ggml-metal-device.m")
    common_h = os.path.join(os.path.dirname(metal_dir.rstrip("/")), "ggml-common.h")
    impl_h = os.path.join(metal_dir, "ggml-metal-impl.h")
    return device_m, common_h, impl_h, os.path.join(metal_dir, "kernels")


def _kinds_checked(device_m: str, kernels_dir: str) -> list:
    kinds = library_kinds(device_m)
    missing = [k for k in kinds if not os.path.isfile(os.path.join(kernels_dir, k + ".metal"))]
    if missing:
        raise RuntimeError(f"GGML_METAL_LIBS names kernels with no source: {missing}")
    return kinds


def generate_metal_embed(target, source, env):
    """SCons Action. source[0] = ggml-metal-device.m; the rest are dependencies."""
    device_m, common_h, impl_h, kernels_dir = _paths(os.path.dirname(str(source[0])))
    kinds = _kinds_checked(device_m, kernels_dir)
    out_path = str(target[0])
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(render_embed(kernels_dir, kinds, common_h, impl_h))
    return None


def metal_embed_sources(metal_dir: str) -> list:
    """Every file the generated embed depends on, for the SCons Command."""
    device_m, common_h, impl_h, kernels = _paths(metal_dir)
    deps = [device_m, common_h, impl_h]
    deps += sorted(os.path.join(kernels, f) for f in os.listdir(kernels) if f.endswith((".metal", ".h")))
    return deps


def check_against_cmake(metal_dir: str, cmake_build: str) -> int:
    """Compare every kind with CMake's autogenerated source. Returns failures."""
    device_m, common_h, impl_h, kernels_dir = _paths(metal_dir)
    kinds = _kinds_checked(device_m, kernels_dir)
    auto = os.path.join(cmake_build, "ggml", "src", "ggml-metal", "autogenerated")
    fails = 0
    for kind in kinds:
        ref_path = os.path.join(auto, f"ggml-metal-embed-{kind}.metal")
        if not os.path.isfile(ref_path):
            print(f"FAIL {kind}: no CMake reference at {ref_path}")
            fails += 1
            continue
        ours = merge_kind(kernels_dir, kind, common_h, impl_h).encode("utf-8")
        ref = open(ref_path, "rb").read()
        if ours != ref:
            print(f"FAIL {kind}: {len(ours)} bytes here, {len(ref)} bytes from CMake")
            fails += 1
    extra = sorted(
        f[len("ggml-metal-embed-") : -len(".metal")]
        for f in os.listdir(auto)
        if f.startswith("ggml-metal-embed-") and f.endswith(".metal")
    )
    unlisted = [k for k in extra if k not in kinds]
    for k in unlisted:
        print(f"FAIL {k}: CMake embeds it but GGML_METAL_LIBS does not list it")
    fails += len(unlisted)
    print(f"{len(kinds)} kinds compared, {fails} failed")
    return fails


if __name__ == "__main__":
    if len(sys.argv) != 3 or sys.argv[1] != "--check":
        sys.exit(__doc__)
    here = os.path.dirname(os.path.abspath(__file__))
    metal = os.path.join(here, "..", "..", "thirdparty", "llama_cpp", "ggml", "src", "ggml-metal")
    sys.exit(1 if check_against_cmake(os.path.normpath(metal), sys.argv[2]) else 0)
